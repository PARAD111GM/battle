import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const base = (process.env.TEST_URL || 'http://127.0.0.1:5173').replace(/\/$/, '');
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(base); await expect(page.locator('#overlay')).toHaveAttribute('data-screen', 'title');
  await page.getByRole('button', { name: 'ENTER THE ARENA' }).click();
  await expect(page.locator('#overlay')).toHaveAttribute('data-screen', 'menu');
  await page.locator('[data-action="setup"]').click();
  await expect(page.locator('.arena-card')).toHaveCount(4);
  await page.locator('[data-action="arena"][data-value="mine"]').click();
  await page.getByLabel('Number of fighters').selectOption('6');
  await page.getByLabel('Mode', { exact: true }).selectOption('stocks');
  await page.getByLabel('Starting stocks').selectOption('1');
  await page.getByLabel('Damage system').selectOption('percent');
  await page.getByLabel('Time limit').selectOption('120');
  await page.getByLabel('Weapons', { exact: true }).selectOption('custom');
  await page.locator('[data-weapon="grenade"]').check();
  await page.getByLabel('Player 2 controller').selectOption('keyboard2');
  await page.getByLabel('Player 3 controller').selectOption('gamepad0');
  await page.getByLabel('Player 4 difficulty').selectOption('expert');
  await page.locator('[data-action="characters"]').click();
  await page.locator('[data-action="character"][data-value="wisp"]').click();
  await page.locator('[data-action="player"][data-value="1"]').click();
  await page.locator('[data-action="character"][data-value="flux"]').click();
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: 'test-results/character-select.png' });
  await page.locator('[data-action="start"]').click();
  await page.waitForFunction(() => window.__RIVETFALL__?.world.tick > 5);
  const setup = await page.evaluate(() => {
    const { world, config } = window.__RIVETFALL__;
    return { arena: world.arena.id, settings: world.settings, characters: world.fighters.map(f => f.character), count: world.fighters.length, humans: world.fighters.filter(f => f.controller === 'human').length, fourthDifficulty: world.fighters[3].difficulty, controller: config.players[2].controller };
  });
  expect(setup.arena).toBe('mine'); expect(setup.count).toBe(6); expect(setup.humans).toBe(3);
  expect(setup.characters[0]).toBe('wisp'); expect(setup.characters[1]).toBe('flux');
  expect(setup.settings).toMatchObject({ mode: 'stocks', stocks: 1, damageMode: 'percent', timeLimit: 120, weaponSet: 'custom' });
  expect(setup.settings.customWeapons).toContain('grenade'); expect(setup.fourthDifficulty).toBe('expert');
  await expect(page.locator('.fighter-hud')).toHaveCount(6);
  await page.keyboard.press('Escape'); await expect(page.locator('#overlay')).toHaveAttribute('data-screen', 'pause');
  const pausedTick = await page.evaluate(() => window.__RIVETFALL__.world.tick);
  await page.waitForTimeout(250); expect(await page.evaluate(() => window.__RIVETFALL__.world.tick)).toBe(pausedTick);
  await page.locator('[data-action="controls"]').click(); await expect(page.locator('.controls-table')).toBeVisible();
  await page.locator('[data-action="back"]').click(); await expect(page.locator('#overlay')).toHaveAttribute('data-screen', 'pause');
  await page.locator('[data-action="resume"]').click();
  await page.waitForFunction(tick => window.__RIVETFALL__.world.tick > tick, pausedTick);
  await page.evaluate(() => {
    const world = window.__RIVETFALL__.world;
    for (const fighter of world.fighters.slice(1)) world.knockout(fighter, 0, 'knockout');
  });
  await expect(page.locator('#overlay')).toHaveAttribute('data-screen', 'results');
  await expect(page.locator('.results-heading h1')).toContainText('WISP WINS');
  await expect(page.locator('.results-table tbody tr')).toHaveCount(6);
  await expect(page.locator('.mvp-banner')).toContainText('WISP');
  await page.screenshot({ path: 'test-results/results.png' });
  await page.locator('[data-action="rematch"]').click();
  await page.waitForFunction(() => window.__RIVETFALL__.world.tick > 3 && !window.__RIVETFALL__.world.match.ended);
  expect(await page.evaluate(() => window.__RIVETFALL__.world.fighters[0].combat.kills)).toBe(0);
  await page.keyboard.press('Escape'); await page.locator('[data-action="menu"]').click();
  await expect(page.locator('#overlay')).toHaveAttribute('data-screen', 'menu');
  await page.screenshot({ path: 'test-results/main-menu.png' });
  await page.reload(); await page.getByRole('button', { name: 'ENTER THE ARENA' }).click(); await page.locator('[data-action="setup"]').click();
  await expect(page.getByLabel('Number of fighters')).toHaveValue('6');
  await expect(page.getByLabel('Mode', { exact: true })).toHaveValue('stocks');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/mobile-setup.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  if (errors.length) throw new Error(errors.join('\n'));
  console.log(JSON.stringify({ flow: 'title/menu/setup/characters/match/pause/controls/results/rematch/menu', setup, persistence: 'passed', mobileOverflow: 'none', pageErrors: errors }, null, 2));
} finally { await browser.close(); }
